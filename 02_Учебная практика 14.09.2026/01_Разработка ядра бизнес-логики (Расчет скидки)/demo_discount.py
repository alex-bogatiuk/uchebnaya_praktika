"""Консольный демонстрационный скрипт для проверки расчета скидки."""

from discount import calculate_partner_discount


def run_demo() -> None:
    """Запуск демонстрационной таблицы расчета скидок."""
    test_cases = [
        (0, "Нулевой объем"),
        (5000, "Менее 10 000"),
        (9999, "Пограничное значение перед 1-м порогом"),
        (10000, "Точная граница 1-го порога (5%)"),
        (25000, "Внутри диапазона 10 000 - 49 999"),
        (49999, "Пограничное значение перед 2-м порогом"),
        (50000, "Точная граница 2-го порога (10%)"),
        (150000, "Внутри диапазона 50 000 - 299 999"),
        (299999, "Пограничное значение перед 3-м порогом"),
        (300000, "Точная граница 3-го порога (15%)"),
        (1000000, "Сверхкрупный объем (15%)"),
    ]

    print("=" * 70)
    print("ДЕМОНСТРАЦИЯ РАСЧЕТА ИНДИВИДУАЛЬНОЙ СКИДКИ ПАРТНЕРА")
    print("=" * 70)
    print(f"{'Объем (ед.)':<15} | {'Скидка':<8} | {'Примечание'}")
    print("-" * 70)

    for quantity, note in test_cases:
        discount = calculate_partner_discount(quantity)
        print(f"{quantity:<15} | {discount:>5}%  | {note}")

    print("=" * 70)


if __name__ == "__main__":
    run_demo()
