"""Демонстрация работы алгоритма расчета материалов с подробной детализацией шагов."""

import sys
from material_calc import calculate_material_consumption, DEFAULT_PRODUCT_TYPES, DEFAULT_MATERIAL_TYPES


def run_demo() -> None:
    print("=" * 75)
    print("ДЕМОНСТРАЦИЯ АЛГОРИТМА РАСЧЕТА СЫРЬЯ ДЛЯ ПРОИЗВОДСТВА")
    print("=" * 75)

    cases = [
        ("Стандартный расчет (Ламинат, тип 1, 100 шт, 1.5 x 2.0)", 1, 1, 100, 1.5, 2.0),
        ("Дробный расчет с проверкой ceil (Паркет, тип 2, 7 шт, 1.1 x 1.1)", 2, 2, 7, 1.1, 1.1),
        ("Несуществующий тип продукции (тип 99)", 99, 1, 50, 1.0, 1.0),
        ("Несуществующий тип материала (тип 88)", 1, 88, 50, 1.0, 1.0),
        ("Отрицательный параметр 1 (-2.5)", 1, 1, 10, -2.5, 1.0),
        ("Отрицательный параметр 2 (-1.0)", 1, 1, 10, 1.0, -1.0),
        ("Нулевое количество продукции (0 шт)", 1, 1, 0, 1.5, 2.0),
        ("Отрицательное количество продукции (-10 шт)", 1, 1, -10, 1.5, 2.0),
    ]

    for title, pt_id, mt_id, qty, p1, p2 in cases:
        res = calculate_material_consumption(pt_id, mt_id, qty, p1, p2)
        status = f"Результат: {res} ед." if res != -1 else "Результат: -1 (Ошибка входных данных)"
        print(f"\nТест-кейс: {title}")
        print(f"  Вход: тип_продукции={pt_id}, тип_материала={mt_id}, кол-во={qty}, p1={p1}, p2={p2}")
        print(f"  -> {status}")

    print("\n" + "=" * 75)


if __name__ == "__main__":
    run_demo()
